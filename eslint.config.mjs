import angular from 'angular-eslint';
import tseslint from 'typescript-eslint';

/**
 * Lints Angular templates only: `.html` files and inline `template:` strings.
 *
 * Oxlint lints all TypeScript and JavaScript (`.oxlintrc.json`), but it cannot parse Angular
 * templates. `pnpm lint` runs both. Template rules need no type information, so this config
 * parses `.ts` files only to extract their inline templates.
 */
export default tseslint.config(
  {
    ignores: [
      '**/dist',
      '**/out-tsc',
      '**/public/keycloakify-dev-resources/**',
      '**/public/keycloak-resources/**',
      // Generated by Keycloakify. It holds no template.
      'apps/koureia-keycloak-theme/src/kc.gen.ts',
    ],
  },
  {
    files: ['**/*.ts'],
    languageOptions: { parser: tseslint.parser },
    processor: angular.processInlineTemplates,
  },
  {
    files: ['**/*.html'],
    extends: [...angular.configs.templateRecommended, ...angular.configs.templateAccessibility],
  },
);
