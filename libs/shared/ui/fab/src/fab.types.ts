/** Edge length of the square button. `md` is the main action, `sm` a second one beside it. */
export type FabSize = 'sm' | 'md' | 'lg';

/** `primary` fills with the brand accent. `secondary` is a raised surface. */
export type FabSeverity = 'primary' | 'secondary';

/** `fixed` pins the group to the viewport. `absolute` pins it to the nearest positioned ancestor. */
export type FabGroupPosition = 'fixed' | 'absolute';
